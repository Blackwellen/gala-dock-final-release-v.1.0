-- Q01 P1 (lane B, 2026-10-29): owner invite / revoke through commands.
-- Client roles hold only SELECT on workspace_invites (least-privilege grants, Q01), so the generic owner invite
-- (/api/invites, onboarding team step, provider Settings → Team invite/revoke) failed with "permission denied".
-- Same authority rule as respond_to_invite and crew_invite_login (202610293014): only the workspace OWNER issues or
-- revokes invitations — respond_to_invite treats any invite whose inviter is not the current owner as revoked, so a
-- manager-issued invite could never be accepted. Managers / members / finance are refused here (not_authorized).
-- The token is generated by the server and only its SHA-256 hash reaches the database; the invite is email-bound and
-- single-use (respond_to_invite checks the email and accepted_at). Additive: new functions only, no grant changes.
create or replace function public.create_workspace_invite(p_workspace uuid, p_email text, p_role text, p_token_hash text)
returns uuid language plpgsql volatile security definer set search_path = '' as $$
declare uid uuid := auth.uid(); em text := lower(btrim(coalesce(p_email, ''))); ws public.workspaces; iid uuid;
begin
  if uid is null then raise exception 'not_authenticated' using errcode = '28000'; end if;
  select * into ws from public.workspaces where id = p_workspace;
  -- Unknown workspace and someone else's workspace look the same (no enumeration).
  if not found or not public.is_workspace_owner(p_workspace) then raise exception 'not_authorized' using errcode = '42501'; end if;
  if not ws.onboarding_complete then raise exception 'workspace_not_ready' using errcode = '55000'; end if;
  if p_role is null or p_role not in ('member', 'manager', 'finance') then raise exception 'invalid_role' using errcode = '22023'; end if;
  if em !~ '^[^@\s]+@[^@\s]+\.[^@\s]{2,}$' or length(em) > 254 then raise exception 'invalid_email' using errcode = '22023'; end if;
  if coalesce(p_token_hash, '') !~ '^[0-9a-f]{64}$' then raise exception 'invalid_token' using errcode = '22023'; end if;
  if em = (select lower(email) from auth.users where id = uid) then raise exception 'self_invite' using errcode = '22023'; end if;
  if exists (select 1 from public.workspace_members m join auth.users u on u.id = m.user_id
             where m.workspace_id = p_workspace and m.status = 'active' and lower(u.email) = em) then
    raise exception 'already_member' using errcode = '23505';
  end if;
  -- Abuse limits: 30 invitations per owner per hour, 100 per workspace per day.
  if not public.hit_rate_limit('ws-invite:u:' || uid::text, 30, 3600)
     or not public.hit_rate_limit('ws-invite:w:' || p_workspace::text, 100, 86400) then
    raise exception 'rate_limited' using errcode = '54000';
  end if;
  insert into public.workspace_invites(workspace_id, email, role, token_hash, invited_by)
    values (p_workspace, em, p_role, p_token_hash, uid) returning id into iid;   -- one pending per email: 23505 from workspace_invites_one_pending
  insert into public.audit_events(actor_id, workspace_id, event, metadata)
    values (uid, p_workspace, 'invite.created', jsonb_build_object('invite_id', iid, 'role', p_role));
  return iid;
end $$;

create or replace function public.revoke_workspace_invite(p_invite uuid)
returns boolean language plpgsql volatile security definer set search_path = '' as $$
declare uid uuid := auth.uid(); inv public.workspace_invites;
begin
  if uid is null then raise exception 'not_authenticated' using errcode = '28000'; end if;
  select * into inv from public.workspace_invites where id = p_invite for update;
  if not found or not public.is_workspace_owner(inv.workspace_id) then raise exception 'not_authorized' using errcode = '42501'; end if;
  if inv.accepted_at is not null then raise exception 'invite_already_used' using errcode = '55000'; end if;
  if inv.revoked_at is not null or inv.declined_at is not null then return false; end if;   -- idempotent
  update public.workspace_invites set revoked_at = now() where id = inv.id;
  insert into public.audit_events(actor_id, workspace_id, event, metadata)
    values (uid, inv.workspace_id, 'invite.revoked', jsonb_build_object('invite_id', inv.id));
  return true;
end $$;

revoke all on function public.create_workspace_invite(uuid, text, text, text), public.revoke_workspace_invite(uuid) from public, anon;
grant execute on function public.create_workspace_invite(uuid, text, text, text), public.revoke_workspace_invite(uuid) to authenticated, service_role;
