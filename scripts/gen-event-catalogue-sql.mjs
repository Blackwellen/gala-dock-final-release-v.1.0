// Generates the domain_event_types seed (Q03) from src/lib/foundation/event-catalogue.ts (Node 24 type stripping).
// Idempotent upsert; entries removed from the catalogue are deactivated, never deleted (stored outbox rows keep their type).
// Usage: node scripts/gen-event-catalogue-sql.mjs   (paste between the GENERATED markers of the workflow-foundation migration)
import { EVENT_CATALOGUE } from "../src/lib/foundation/event-catalogue.ts";

const q = s => s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`;
const types = new Set();
for (const e of EVENT_CATALOGUE) {
  if (!/^[a-z][a-z0-9_]*(\.[a-z0-9_]+)+$/.test(e.type)) throw new Error(`Bad event type ${e.type}`);
  if (types.has(e.type)) throw new Error(`Duplicate event type ${e.type}`);
  types.add(e.type);
}
console.log([
  "-- ═══ GENERATED by scripts/gen-event-catalogue-sql.mjs from src/lib/foundation/event-catalogue.ts — do not edit by hand ═══",
  `insert into public.domain_event_types(event_type, schema_version, aggregate, description, public_type) values\n  ${EVENT_CATALOGUE.map(e => `(${[q(e.type), e.schemaVersion, q(e.aggregate), q(e.description), q(e.publicType ?? null)].join(", ")})`).join(",\n  ")}\non conflict (event_type) do update set schema_version = excluded.schema_version, aggregate = excluded.aggregate, description = excluded.description, public_type = excluded.public_type, active = true, updated_at = now();`,
  `update public.domain_event_types set active = false, updated_at = now() where event_type <> all (array[${EVENT_CATALOGUE.map(e => q(e.type)).join(", ")}]::text[]) and active;`,
  "-- ═══ END GENERATED ═══",
].join("\n"));
