// Generates the seed section of the foundation migration from the TypeScript source of truth
// (src/lib/domain/permissions.ts and state-machines.ts), so database guards and app code never drift.
// Usage: node scripts/gen-foundation-sql.mjs > supabase/migrations/<ts>_foundation_seed.sql
import { rolePermissions } from "../src/lib/domain/permissions.ts";
import { machines } from "../src/lib/domain/state-machines.ts";

const q = s => `'${String(s).replace(/'/g, "''")}'`;
const out = ["-- GENERATED by scripts/gen-foundation-sql.mjs — do not edit by hand.", "begin;", "delete from public.role_permissions;"];
const perms = [];
for (const [kind, roles] of Object.entries(rolePermissions))
  for (const [role, list] of Object.entries(roles)) for (const p of list) perms.push(`(${q(kind)},${q(role)},${q(p)})`);
out.push(`insert into public.role_permissions(workspace_kind, role, permission) values\n  ${perms.join(",\n  ")};`);

out.push("delete from public.state_transitions;", "delete from public.state_machines;");
for (const [name, m] of Object.entries(machines)) {
  out.push(`insert into public.state_machines(machine, table_name, column_name, mode, initial_states, terminal_states) values (${q(name)}, ${q(m.table)}, ${q(m.column)}, ${q(m.mode)}, array[${m.initial.map(q).join(",")}]::text[], array[${m.terminal.map(q).join(",")}]::text[]);`);
  const rows = [];
  for (const [from, tos] of Object.entries(m.transitions)) for (const to of tos) rows.push(`(${q(name)},${q(from)},${q(to)})`);
  if (rows.length) out.push(`insert into public.state_transitions(machine, from_state, to_state) values\n  ${rows.join(",\n  ")};`);
  out.push(`drop trigger if exists ${m.table}_state_guard on public.${m.table};`,
    `create trigger ${m.table}_state_guard before insert or update of ${m.column} on public.${m.table} for each row execute function public.enforce_state_transition(${q(name)}, ${q(m.column)});`);
}
out.push("commit;");
console.log(out.join("\n"));
