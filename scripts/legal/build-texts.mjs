#!/usr/bin/env node
// Legal sign-off (R3, 2026-11-15): compiles the published legal texts (content/legal/<slug>.md) into src/lib/legal/texts.generated.ts
// with a sha256 of each body, after the publication checks the playbook (§4) requires. Refuses to write if any check fails:
//   - every file has frontmatter (title, summary) and a registry entry with the same title (src/lib/legal/registry.ts), and vice versa;
//   - no draft markers, square-bracket placeholders, review annotations or engine notes;
//   - no person named in a header, contact point or signature (role wording only: "our data protection lead", "our Safeguarding lead");
//   - insurance wording only in the clauses that impose an obligation on sellers to hold their own cover (owner 2026-11-15).
// Usage: node scripts/legal/build-texts.mjs           write the module
//        node scripts/legal/build-texts.mjs --check   exit 1 if the module is out of date or a check fails (CI / spec)
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const DIR = join(process.cwd(), "content", "legal");
const OUT = join(process.cwd(), "src", "lib", "legal", "texts.generated.ts");
const REGISTRY = readFileSync(join(process.cwd(), "src", "lib", "legal", "registry.ts"), "utf8");
const registry = new Map([...REGISTRY.matchAll(/\{ slug: "([a-z-]+)", title: "([^"]+)"/g)].map(m => [m[1], m[2]]));

/** Insurance may be mentioned only where a seller must hold its own cover, or where we say what our insurance badge checked. */
export const INSURANCE_ALLOWED = ["terms", "organiser-terms", "supplier-terms", "venue-terms", "community-standards"];
const FORBIDDEN = [
  [/\bDRAFT\b|not in force, not published|[Aa]waiting approval|[Dd]raft for owner review/, "draft marker"],
  [/\[(?![^\]]*\]\()/, "square-bracket placeholder (only [text](link) is allowed)"],
  [/\bENGINE\b|owner decision|counsel|\bQ\d{2}\b|behaviour-mismatches|to be confirmed/i, "review annotation"],
  [/jamahl|\bthomas\b/i, "a person's name"],
  [/Data Protection Officer|\bDPO\b/, "named officer title (use \"our data protection lead\")"],
];

const problems = [];
const texts = {};
const files = readdirSync(DIR).filter(f => f.endsWith(".md")).sort();
for (const f of files) {
  const slug = f.slice(0, -3);
  const raw = readFileSync(join(DIR, f), "utf8").replace(/\r\n?/g, "\n");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) { problems.push(`${f}: missing frontmatter`); continue; }
  const meta = Object.fromEntries(m[1].split("\n").map(l => l.match(/^(\w+):\s*(.*)$/)).filter(Boolean).map(x => [x[1], x[2].trim()]));
  const body = m[2].trim() + "\n";
  if (!meta.title || !meta.summary) problems.push(`${f}: frontmatter needs title and summary`);
  if (!registry.has(slug)) problems.push(`${f}: no registry entry for "${slug}"`);
  else if (registry.get(slug) !== meta.title) problems.push(`${f}: title "${meta.title}" ≠ registry "${registry.get(slug)}"`);
  body.split("\n").forEach((line, i) => {
    for (const [re, what] of FORBIDDEN) if (re.test(line)) problems.push(`${f}:${i + 1}: ${what}: ${line.slice(0, 120)}`);
    if (/insur/i.test(line.replace(/National Insurance/g, "")) && !INSURANCE_ALLOWED.includes(slug)) problems.push(`${f}:${i + 1}: insurance wording outside a seller-obligation clause: ${line.slice(0, 120)}`);
  });
  if (body.length < 400) problems.push(`${f}: body too short to publish`);
  texts[slug] = { title: meta.title, summary: meta.summary, body, sha256: createHash("sha256").update(body).digest("hex") };
}
for (const slug of registry.keys()) if (!texts[slug] && !problems.some(p => p.startsWith(`${slug}.md`))) problems.push(`registry "${slug}" has no content/legal/${slug}.md`);

if (problems.length) { console.error(`Legal texts refused (${problems.length}):\n- ${problems.join("\n- ")}`); process.exit(1); }

const out = `// GENERATED by scripts/legal/build-texts.mjs from content/legal/*.md — do not edit by hand. Run \`npm run legal:texts\`.
// sha256 is of the body exactly as published; the database records it for each version when the pack is published.
export type LegalText = { title: string; summary: string; body: string; sha256: string };
export const LEGAL_TEXTS: Record<string, LegalText> = ${JSON.stringify(texts, null, 1)};
`;
if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n?/g, "\n") : "";
  if (cur !== out) { console.error("src/lib/legal/texts.generated.ts is out of date: run npm run legal:texts"); process.exit(1); }
  console.log(`legal texts OK: ${files.length} documents, generated module up to date`);
} else {
  writeFileSync(OUT, out);
  const kept = Object.entries(texts).map(([s, t]) => [s, t.body.split("\n").filter(l => /insur/i.test(l.replace(/National Insurance/g, ""))).length]).filter(([, n]) => n);
  console.log(`wrote ${OUT} (${files.length} documents). Insurance lines kept (seller obligations / badge meaning): ${kept.map(([s, n]) => `${s} ${n}`).join(", ")}`);
}
